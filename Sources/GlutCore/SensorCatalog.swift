    public static func describe(_ key: String, chip: String) -> (String, SensorGroup) {
        let generation = chip.contains("Apple A18") ? 18 : ((1...6).first { chip.contains("Apple M\($0)") } ?? 0)
        if let entry = entries.first(where: { $0.key == key && ($0.generation == -1 || $0.generation == generation) }) {
            return (entry.name, entry.group)
        }
        if key.hasPrefix("TB") || key.hasPrefix("Tb") { return ("Battery · " + key, .battery) }
        if key.hasPrefix("Tg") || key.hasPrefix("TG") { return ("GPU · " + key, .gpu) }
        if key.hasPrefix("TC") || (generation > 0 && ["Tp", "Te"].contains(String(key.prefix(2)))) {
            return ("CPU · " + key, .cpu)
        }
        if key.hasPrefix("Tm") || key.hasPrefix("TM") { return ("Memory · " + key, .memory) }
        if key.hasPrefix("TH") { return ("Storage · " + key, .storage) }
        return ("Sensor " + key, .other)
    }
